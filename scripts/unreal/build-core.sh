#!/usr/bin/env bash
# Build vibe-land's client core as the static library the Unreal plugin links.
#
#   scripts/unreal/build-core.sh [--platform Mac] [--profile release|debug] [--out DIR]
#
# Output (DIR defaults to the plugin's ThirdParty folder):
#   DIR/lib/<Platform>/<arch>/libvibe_client_core.a
#   DIR/lib/<Platform>/<arch>/native-libs.txt     system libraries/frameworks the .a needs
#   DIR/lib/<Platform>/<arch>/vibe_client_core.stamp  header sha256 + git commit of this build
#
# The header is not copied: the plugin includes client-core-ffi/include directly, so there is one
# header, generated and drift-checked by client-core-ffi/tests/header_current.rs.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PLATFORM=""
PROFILE="release"
OUT="$ROOT/unreal/VibeCity/Plugins/VibeLand/Source/ThirdParty/VibeClientCore"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --platform) PLATFORM="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) echo "build-core: unknown argument $1" >&2; exit 2 ;;
  esac
done

if [[ -z "$PLATFORM" ]]; then
  case "$(uname -s)" in
    Darwin) PLATFORM=Mac ;;
    Linux) PLATFORM=Linux ;;
    *) echo "build-core: unsupported host $(uname -s); pass --platform" >&2; exit 2 ;;
  esac
fi

case "$PLATFORM" in
  Mac) TRIPLE=aarch64-apple-darwin; ARCH=arm64; LIB=libvibe_client_core.a
       export MACOSX_DEPLOYMENT_TARGET=14.0 ;;  # matches UE 5.8's arm64-apple-macos14.00
  Linux) TRIPLE=x86_64-unknown-linux-gnu; ARCH=x86_64; LIB=libvibe_client_core.a ;;
  Win64) TRIPLE=x86_64-pc-windows-msvc; ARCH=x64; LIB=vibe_client_core.lib ;;
  *) echo "build-core: unknown platform $PLATFORM" >&2; exit 2 ;;
esac

# UBT launched from the editor may not inherit the shell PATH.
CARGO="${VIBE_CARGO:-}"
if [[ -z "$CARGO" ]]; then
  if command -v cargo >/dev/null 2>&1; then CARGO="$(command -v cargo)"; else CARGO="$HOME/.cargo/bin/cargo"; fi
fi
[[ -x "$CARGO" ]] || { echo "build-core: cargo not found (set VIBE_CARGO)" >&2; exit 1; }

PKG=vibe-client-core-ffi
PROFILE_FLAG=(); PROFILE_DIR=debug
if [[ "$PROFILE" == release ]]; then PROFILE_FLAG=(--release); PROFILE_DIR=release; fi

cd "$ROOT"

# Always -p: building the whole workspace unifies features and would pull the server's TLS stack
# (aws-lc) into the static library.
if "$CARGO" tree -p "$PKG" --target "$TRIPLE" -e normal --prefix none 2>/dev/null | grep -q '^aws-lc'; then
  echo "build-core: aws-lc is in $PKG's dependency tree; the client core must use ring only" >&2
  exit 1
fi

# Build the staticlib and capture the native libraries it needs in one compile.
NATIVE_LOG="$(mktemp)"
trap 'rm -f "$NATIVE_LOG"' EXIT
"$CARGO" rustc -p "$PKG" --lib "${PROFILE_FLAG[@]}" --target "$TRIPLE" --crate-type staticlib \
  -- --print native-static-libs 2> >(tee "$NATIVE_LOG" >&2)

DEST="$OUT/lib/$PLATFORM/$ARCH"
mkdir -p "$DEST"
cp "$ROOT/target/$TRIPLE/$PROFILE_DIR/$LIB" "$DEST/$LIB"

NATIVE="$(sed -n 's/.*native-static-libs: //p' "$NATIVE_LOG" | tail -1)"
printf '%s\n' "$NATIVE" > "$DEST/native-libs.txt"

# UBT does not relink a module when only a static library it links changed. A generated header
# carrying the library's hash, rewritten only when the library changes, makes the module that
# includes it (VibeLandNet) recompile and relink against the new library.
LIB_SHA="$(shasum -a 256 "$DEST/$LIB" | cut -d' ' -f1)"
GEN="$OUT/include-gen"
mkdir -p "$GEN"
BUILD_H="$GEN/vibe_client_core_build.h"
NEW_H="$(printf '#pragma once\n/* Generated by scripts/unreal/build-core.sh: the linked client core library. */\n#define VL_CORE_LIB_SHA256 "%s"\n' "$LIB_SHA")"
if [[ ! -f "$BUILD_H" ]] || [[ "$(cat "$BUILD_H")" != "$NEW_H" ]]; then
  printf '%s\n' "$NEW_H" > "$BUILD_H"
fi

HEADER="$ROOT/client-core-ffi/include/vibe_client_core.h"
HEADER_SHA="$(shasum -a 256 "$HEADER" | cut -d' ' -f1)"
GIT_SHA="$(git -C "$ROOT" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"
printf 'header_sha256=%s\ngit=%s\ntarget=%s\nprofile=%s\n' "$HEADER_SHA" "$GIT_SHA" "$TRIPLE" "$PROFILE" > "$DEST/vibe_client_core.stamp"

echo "build-core: $DEST/$LIB ($(du -h "$DEST/$LIB" | cut -f1)); native libs: ${NATIVE:-none}"
