import { open, banner, caption, liveStats, snap, sleep } from './session.mjs';
import { dumpFps } from './session.mjs';
import { mark, walkTo, driveTo, enterNearest } from './nav.mjs';
const OUT = process.argv[2];
const { browser, context, page, renderer } = await open({ path: '/play?match=default', record: OUT });
mark(`joined; renderer ${renderer}`);
await banner(page, 'vibe-land on a Mac: PhysX GPU rigid bodies on Apple Silicon (Metal, via CuMetal)');
const stop = liveStats(page, 'default');
await caption(page, 'Heightfield terrain: a player (kinematic capsule) walks over the hills to the balls');
await sleep(3000);
await walkTo(page, 14, 16, { within: 3 });
mark('at the balls');
await caption(page, 'Walking into 50 dynamic balls resting on the heightfield');
await walkTo(page, 9, 9, { within: 2, sprint: false, timeoutMs: 8000 });
await sleep(1500);
await caption(page, 'Walking to the car');
let s = await snap(page);
const me = s.position;
const v = (s.vehicles || []).reduce((a, b) => (Math.hypot(a.position[0] - me[0], a.position[2] - me[2]) < Math.hypot(b.position[0] - me[0], b.position[2] - me[2]) ? a : b));
const car = v.id;
mark(`vehicles ${JSON.stringify(s.vehicles)}`);
await walkTo(page, v.position[0] + 2.5, v.position[2] - 1.5, { within: 2, timeoutMs: 20000 });
const inCar = await enterNearest(page, car);
mark(`in car: ${inCar}`);
if (!inCar) { await browser.close(); process.exit(1); }
await caption(page, 'Driving over the heightfield: Vehicle2 suspension + tyre constraint rows solved on the GPU');
const top = await driveTo(page, car, [[40, 10], [60, -30], [20, -55], [-20, -30], [-10, 10], [11, 11], [30, 30]], { log: mark });
mark(`max speed ${top.toFixed(1)} m/s`);
await caption(page, 'Balls knocked by the car settle back onto the terrain');
await sleep(5000);
const final = await (await fetch('http://127.0.0.1:4001/match-stats/default')).json();
mark(`final gpu_active=${final.physics_gpu_active} warnings=${final.physics_gpu_warning_count}`);
stop();
await dumpFps(page);
const video = page.video();
await context.close();
await browser.close();
if (video) console.log('video', await video.path());
